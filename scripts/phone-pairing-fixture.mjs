#!/usr/bin/env node
// Generates test/fixtures/phone-pairing-v1.json: the shared test vectors for
// docs/PHONE_PAIRING.md, consumed by test/services/phonePairing.test.js and
// by the iOS PhonePairingVectorTests. Deterministic: every random input is
// fixed below, so re-running produces the same file. Pass a path as the first
// argument to also write the Swift literal the iOS test embeds.
//
//   node scripts/phone-pairing-fixture.mjs [path/to/PhonePairingFixture.swift]

import { createECDH } from 'node:crypto';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
    bytesToBase64Url, importPrivateKeyJwk, ecdh, deriveK1, deriveK2,
    sealMsg1, sealMsg2, encodePhoneMessage, encodeComputerMessage, encodeQr
} from '../chat/services/phonePairing.js';

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../test/fixtures/phone-pairing-v1.json');

const hex = s => Uint8Array.from(Buffer.from(s, 'hex'));
// Fixed inputs. Not secrets: this is a published test vector.
const tunnelId = hex('0f1e2d3c4b5a69788796a5b4c3d2e1f0');
const qrSecret = hex('a0a1a2a3a4a5a6a7a8a9aaabacadaeafb0b1b2b3b4b5b6b7b8b9babbbcbdbebf');
const cPriv = hex('c1c2c3c4c5c6c7c8c9cacbcccdcecfd0d1d2d3d4d5d6d7d8d9dadbdcdddedfe0');
const pPriv = hex('7171717171717171717171717171717171717171717171717171717171717171');
const nonce1 = hex('101112131415161718191a1b');
const nonce2 = hex('202122232425262728292a2b');
const masterKey = hex('4d4d4d4d4d4d4d4d4d4d4d4d4d4d4d4d4d4d4d4d4d4d4d4d4d4d4d4d4d4d4d4d');
const grant = 'Z3JhbnQtZm9yLXRoZS1maXh0dXJlLW9ubHktMDAwMDAwMDA';
const accountId = '1234567890123456';

function jwkFor(priv) {
    const ec = createECDH('prime256v1');
    ec.setPrivateKey(Buffer.from(priv));
    const pub = ec.getPublicKey(); // 65 bytes, uncompressed
    return {
        jwk: { kty: 'EC', crv: 'P-256', d: bytesToBase64Url(priv), x: bytesToBase64Url(pub.subarray(1, 33)), y: bytesToBase64Url(pub.subarray(33, 65)), ext: true },
        pub: new Uint8Array(pub)
    };
}

const computer = jwkFor(cPriv);
const phone = jwkFor(pPriv);
const cKey = await importPrivateKeyJwk(computer.jwk);
const pKey = await importPrivateKeyJwk(phone.jwk);

const sharedFromComputer = await ecdh(cKey, phone.pub);
const sharedFromPhone = await ecdh(pKey, computer.pub);
if (Buffer.compare(sharedFromComputer, sharedFromPhone) !== 0) throw new Error('ECDH mismatch');

const k1 = await deriveK1({ qrSecret, tunnelId });
const k2 = await deriveK2({ shared: sharedFromComputer, qrSecret, tunnelId, cPub: computer.pub, pPub: phone.pub });

const msg1Plain = encodePhoneMessage({ pPub: phone.pub, kind: 'username', accountId, device: 'iPhone' });
const msg2Plain = encodeComputerMessage({ masterKey, grant });
const msg1 = await sealMsg1({ k1, tunnelId, nonce: nonce1, plaintext: msg1Plain });
const msg2 = await sealMsg2({ k2, tunnelId, nonce: nonce2, plaintext: msg2Plain });

const b = bytesToBase64Url;
const fixture = {
    _comment: 'Shared test vectors for docs/PHONE_PAIRING.md v1. Generated by scripts/phone-pairing-fixture.mjs; do not edit by hand. Bytes are base64url without padding.',
    version: 1,
    tunnelId: b(tunnelId),
    qrSecret: b(qrSecret),
    computer: { privateScalar: b(cPriv), pub: b(computer.pub) },
    phone: { privateScalar: b(pPriv), pub: b(phone.pub) },
    shared: b(sharedFromComputer),
    k1: b(k1),
    k2: b(k2),
    qr: encodeQr({ env: 'staging', tunnelId, qrSecret, cPub: computer.pub }),
    msg1: { nonce: b(nonce1), plaintext: b(msg1Plain), plaintextUtf8: Buffer.from(msg1Plain).toString('utf8'), ciphertext: b(msg1) },
    msg2: { nonce: b(nonce2), plaintext: b(msg2Plain), plaintextUtf8: Buffer.from(msg2Plain).toString('utf8'), ciphertext: b(msg2) },
    expected: { kind: 'username', accountId, device: 'iPhone', masterKey: b(masterKey), grant }
};

mkdirSync(dirname(out), { recursive: true });
const json = JSON.stringify(fixture, null, 2) + '\n';
writeFileSync(out, json);
console.log(`wrote ${out}`);

const swiftPath = process.argv[2];
if (swiftPath) {
    const swift = `// Generated by oa-chat scripts/phone-pairing-fixture.mjs. Do not edit.
// The same bytes as oa-chat test/fixtures/phone-pairing-v1.json.
enum PhonePairingFixture {
    static let json = #"""
${json.trimEnd()}
"""#
}
`;
    writeFileSync(swiftPath, swift);
    console.log(`wrote ${swiftPath}`);
}
